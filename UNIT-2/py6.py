fruits = ["Apple", "Banana", "Mango", "Orange"]
print("List elements:")
for fruit in fruits:
    print(fruit)
name = "Python"
print("\nString characters:")
for character in name:
    print(character)
student = {
    "Name": "Rahul",
    "Age": 20,
    "Course": "Python"
}
print("\nDictionary elements:")
for key, value in student.items():
    print(key, ":", value)
